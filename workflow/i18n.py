#!/usr/bin/env python3
"""Traductions des textes de notification, alignées sur la langue de macOS.

Langues : fr, en, it, de, pt, es, ja, zh, el. Repli : en, puis fr.
Détection via AppleLocale (puis AppleLanguages) ; np_lang la force si posée.
"""

import os
import re
import subprocess

SUPPORTED = ("fr", "en", "it", "de", "pt", "es", "ja", "zh", "el")

_cached_lang = None


def _detect():
    forced = (os.environ.get("np_lang") or "").strip().lower()[:2]
    if forced in SUPPORTED:
        return forced
    for domain_key in ("AppleLocale", "AppleLanguages"):
        try:
            result = subprocess.run(
                ["defaults", "read", "-g", domain_key],
                capture_output=True,
                text=True,
                timeout=3,
            )
            match = re.search(r"[a-zA-Z]{2}", result.stdout)
            if match:
                code = match.group(0).lower()
                if code in SUPPORTED:
                    return code
        except Exception:
            pass
    return "en"


def lang():
    global _cached_lang
    if _cached_lang is None:
        _cached_lang = _detect()
    return _cached_lang


def t(key, *args):
    entry = TABLE.get(key) or {}
    template = entry.get(lang()) or entry.get("en") or entry.get("fr") or key
    return template.format(*args) if args else template


